AS SELECT CUSTOMERS.CUSTOMER_NAME, RESTAURANTS.RESTAURANT_NAME, MENU.ITEM_NAME,ORDERS.QUANTITY, ORDERS.ORDER_STATUS 
FROM CUSTOMERS JOIN ORDERS ON CUSTOMERS.CUSTOMER_ID = ORDERS.CUSTOMER_ID 
JOIN MENU ON ORDERS.MENU_ID = MENU.MENU_ID 
JOIN RESTAURANTS ON MENU.RESTAURANT_ID = RESTAURANTS.RESTAURANT_ID;
SELECT * FROM CUSTOMER_ORDER_HISTORY;

# 31. Create a view named Restaurant_Revenue displaying restaurant name, total orders, and total revenue.
CREATE VIEW RESTAURANT_REVENUE AS SELECT RESTAURANTS.RESTAURANT_NAME, COUNT(DISTINCT ORDERS.ORDER_ID) 
AS TOTAL_ORDERS,SUM(PAYMENTS.AMOUNT) AS TOTAL_REVENUE
FROM RESTAURANTS JOIN MENU ON RESTAURANTS.RESTAURANT_ID = MENU.RESTAURANT_ID
JOIN ORDERS ON MENU.MENU_ID = ORDERS.MENU_ID
JOIN PAYMENTS ON PAYMENTS.ORDER_ID = ORDERS.ORDER_ID
GROUP BY RESTAURANTS.RESTAURANT_NAME;
SELECT * FROM RESTAURANT_REVENUE;

